def new_document(title):
    doc = Document()
    props = doc.core_properties
    props.title, props.author, props.created, props.modified = title, "Тестовый корпус", FIXED_DATE, FIXED_DATE
    return doc


def para(doc, text, style=None, bold_prefix=None, italic=False):
    p = doc.add_paragraph(style=style)
    if bold_prefix:
        p.add_run(bold_prefix).bold = True
    run = p.add_run(text)
    run.italic = italic
    return p


def table(doc, header, rows, caption=None, merged_title=None):
    if caption:
        para(doc, caption, bold_prefix=None).runs[0].bold = True
    n_cols = len(header)
    t = doc.add_table(rows=0, cols=n_cols)
    t.style = "Table Grid"
    if merged_title:  # строка-заголовок, объединённая по всем столбцам
        cells = t.add_row().cells
        merged = cells[0].merge(cells[-1])
        merged.text = merged_title
        merged.paragraphs[0].runs[0].bold = True
    cells = t.add_row().cells
    for c, h in zip(cells, header):
        c.text = h
        c.paragraphs[0].runs[0].bold = True
    for r in rows:
        for c, v in zip(t.add_row().cells, r):
            c.text = v
    doc.add_paragraph()
    return t


def stamp_image(path):
    """Рисунок с текстом (имитация оттиска пробирного клейма): текст внутри изображения."""
    img = Image.new("RGB", (360, 160), "white")
    d = ImageDraw.Draw(img)
    d.ellipse((10, 10, 350, 150), outline="black", width=4)
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial.ttf", 44)
    except OSError:
        font = ImageFont.load_default()
    d.text((70, 55), "ПРОБА 585", fill="black", font=font)
    img.save(path)


